    /// The single pixel of a 1x1 image, as (r, g, b).
    fn pixel_of(data: &[u8]) -> (u8, u8, u8) {
        let rgb = image::load_from_memory(data).unwrap().to_rgb8();
        assert_eq!((rgb.width(), rgb.height()), (1, 1));
        let c = rgb.get_pixel(0, 0).channels();
        (c[0], c[1], c[2])
    }

    /// Encodes a pixel buffer as PNG.
    fn to_png(img: &RgbaImage) -> Vec<u8> {
        let mut png = Vec::new();
        image::codecs::png::PngEncoder::new(&mut png)
            .write_image(
                img.as_raw(),
                img.width(),
                img.height(),
                image::ExtendedColorType::Rgba8,
            )
            .unwrap();
        png
    }

    fn close(a: u8, b: u8) -> bool {
        (a as i32 - b as i32).unsigned_abs() <= 20
    }

    #[test]
    fn sniff_recognises_known_formats() {
        assert_eq!(
            sniff_mime(&[0x89, b'P', b'N', b'G', 0, 0, 0, 0]),
            Some("image/png")
        );
        assert_eq!(sniff_mime(&[0xFF, 0xD8, 0xFF, 0xE0]), Some("image/jpeg"));
        assert_eq!(sniff_mime(b"GIF89a"), Some("image/gif"));
        assert_eq!(sniff_mime(b"BMxxxx"), Some("image/bmp"));
        assert_eq!(sniff_mime(WEBP_1X1), Some("image/webp"));
        assert_eq!(
            sniff_mime(&[0, 0, 0, 24, b'f', b't', b'y', b'p', b'a', b'v', b'i', b'f']),
            Some("image/avif")
        );
        assert_eq!(
            sniff_mime(&[0, 0, 0, 24, b'f', b't', b'y', b'p', b'a', b'v', b'i', b's']),
            Some("image/avif")
        );
        assert_eq!(sniff_mime(b"II*\0"), Some("image/tiff"));
        assert_eq!(sniff_mime(b"MM\0*"), Some("image/tiff"));
    }

    #[test]
    fn sniff_rejects_non_images() {
        assert_eq!(sniff_mime(b"<html>"), None);
        assert_eq!(sniff_mime(b"RIIF\x00\x00"), None);
        assert_eq!(sniff_mime(b""), None);
        assert_eq!(sniff_mime(&[0xFF, 0xD8]), None);
        // A RIFF container is only recognised with the WEBP fourcc.
        assert_eq!(sniff_mime(b"RIFF\x1c\x00\x00\x00AVI "), None);
        // An ftyp box with another brand is not AVIF.
        assert_eq!(
            sniff_mime(&[0, 0, 0, 24, b'f', b't', b'y', b'p', b'M', b'4', b'V', b' ']),
            None
        );
    }

    #[test]
    fn jpeg_and_png_pass_through_untouched() {
        let pixel = RgbaImage::from_pixel(1, 1, image::Rgba([255, 0, 0, 255]));
        let mut jpeg = Vec::new();
        image::codecs::jpeg::JpegEncoder::new(&mut jpeg)
            .encode_image(&pixel)
            .unwrap();
        assert_eq!(normalize_art(&jpeg).unwrap(), jpeg);
        let png = to_png(&pixel);
        assert_eq!(normalize_art(&png).unwrap(), png);
    }

    #[test]
    fn webp_is_converted_to_jpeg() {
        let out = normalize_art(WEBP_1X1).unwrap();
        assert!(out.starts_with(&[0xFF, 0xD8, 0xFF]));
        let (r, g, b) = pixel_of(&out);
        assert!(close(r, 254) && g <= 20 && b <= 20);
    }

    #[test]
    fn webp_alpha_is_flattened_onto_white() {
        let out = normalize_art(WEBP_1X1_ALPHA).unwrap();
        assert!(out.starts_with(&[0xFF, 0xD8, 0xFF]));
        // Red at 50% alpha over white is (255, 128, 128).
        let (r, g, b) = pixel_of(&out);
        assert!(close(r, 255) && close(g, 128) && close(b, 128));
    }

    #[test]
    fn gif_is_converted_to_jpeg() {
        let (r, g, b) = pixel_of(&normalize_art(GIF_1X1).unwrap());
        assert!(r <= 20 && g <= 20 && close(b, 255));
    }

    #[test]
    fn bmp_is_converted_to_jpeg() {
        let (r, g, b) = pixel_of(&normalize_art(BMP_1X1).unwrap());
        assert!(r <= 20 && close(g, 128) && b <= 20);
    }

    #[test]
    fn oversized_art_is_downscaled() {
        let big = RgbaImage::from_pixel(1500, 1000, image::Rgba([255, 0, 0, 255]));
        let out = normalize_art(&to_png(&big)).unwrap();
        let (r, g, b) = pixel_of_scaled(&out);
        assert!(close(r, 255) && g <= 20 && b <= 20);
    }

    /// The dimensions and a middle pixel of a scaled-down image.
    fn pixel_of_scaled(data: &[u8]) -> (u8, u8, u8) {
        let rgb = image::load_from_memory(data).unwrap().to_rgb8();
        assert!(rgb.width() <= 1000 && rgb.height() <= 1000);
        assert_eq!(rgb.width(), 1000);
        // 1500x1000 scaled into a 1000x1000 box keeps the 3:2 ratio.
        assert!((rgb.height() as f32 / rgb.width() as f32 - 2.0 / 3.0).abs() < 0.01);
        let c = rgb.get_pixel(500, 333).channels();
        (c[0], c[1], c[2])
    }

    #[test]
    fn garbage_is_rejected() {
        assert!(normalize_art(b"not an image").is_err());
        assert!(normalize_art(b"").is_err());
        // A valid header that truncates mid-stream is rejected too.
        assert!(normalize_art(&WEBP_1X1[..10]).is_err());
    }
