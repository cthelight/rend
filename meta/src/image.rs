//! Cover art helpers shared by the front ends.
//!
//! A front end (the web UI today, the terminal UI later) can let the user
//! supply their own cover art instead of the one fetched from the Cover Art
//! Archive. [`sniff_mime`] recognises the format of raw image bytes so a
//! front end can reject data that is not a picture, [`fetch_image`] pulls
//! the bytes of an image from an arbitrary URL the user provides, and
//! [`normalize_art`] re-encodes art in a format the tag containers carry
//! well before it is embedded into a track file.

use std::time::Duration;

use ureq::config::Config;
use ureq::{Agent, Error as HttpError};

use crate::lookup::Error;

/// How long a single image request may run before it is dropped.
const TIMEOUT: Duration = Duration::from_secs(15);

/// Recognise the image format of `bytes` by its magic number.
///
/// Returns the MIME type when the bytes look like a picture [`normalize_art`]
/// can embed in a tag, and `None` otherwise.
pub fn sniff_mime(bytes: &[u8]) -> Option<&'static str> {
    if bytes.starts_with(&[0x89, b'P', b'N', b'G']) {
        Some("image/png")
    } else if bytes.starts_with(&[0xFF, 0xD8, 0xFF]) {
        Some("image/jpeg")
    } else if bytes.starts_with(b"GIF8") {
        Some("image/gif")
    } else if bytes.starts_with(b"BM") {
        Some("image/bmp")
    } else if bytes.starts_with(b"RIFF") && bytes.get(8..12) == Some(b"WEBP") {
        Some("image/webp")
    } else if bytes.get(4..8) == Some(b"ftyp")
        && matches!(bytes.get(8..12), Some(b"avif") | Some(b"avis"))
    {
        Some("image/avif")
    } else if bytes.starts_with(b"II*\0") || bytes.starts_with(b"MM\0*") {
        Some("image/tiff")
    } else {
        None
    }
}

/// The longest side, in pixels, of cover art embedded in a track file.
///
/// Bigger art is downscaled before embedding: the picture is written into
/// every track of the rip, so an oversized scan would bloat the whole album.
/// JPEG and PNG art at or under this size passes through untouched.
const MAX_DIMENSION: u32 = 1000;

/// An error while re-encoding cover art.
#[derive(Debug, thiserror::Error)]
pub enum ImageError {
    /// The bytes are not a decodable image.
    #[error("the image could not be decoded: {0}")]
    Decode(#[from] image::ImageError),
}

/// Re-encodes `art` into a form suitable for embedding in a track file's
/// tags, returning the new bytes.
///
/// The tag containers only really carry two formats: the MP4 `covr` atom
/// defines JPEG and PNG and nothing else, and the ID3v2 and FLAC picture
/// specs recommend the same pair. JPEG and PNG art passes through
/// byte-for-byte (it is already ideal); anything else — WebP, AVIF, GIF,
/// BMP, TIFF, … — is decoded and written out as JPEG. Any transparency is
/// flattened onto white, and art longer than [`MAX_DIMENSION`] pixels on a
/// side is downscaled first.
pub fn normalize_art(art: &[u8]) -> Result<Vec<u8>, ImageError> {
    let decoded = image::load_from_memory(art)?;
    let small = decoded.width() <= MAX_DIMENSION && decoded.height() <= MAX_DIMENSION;
    if small && matches!(sniff_mime(art), Some("image/jpeg") | Some("image/png")) {
        return Ok(art.to_vec());
    }

    let decoded = if small {
        decoded
    } else {
        // Shrink to fit within the cap, keeping the aspect ratio.
        decoded.thumbnail(MAX_DIMENSION, MAX_DIMENSION)
    };

    // JPEG has no alpha channel, so blend transparency onto white.
    let rgba = decoded.to_rgba8();
    let mut flat = image::RgbaImage::new(rgba.width(), rgba.height());
    for (x, y, px) in rgba.enumerate_pixels() {
        let a = px[3] as u32;
        let blend = |c: u8| ((c as u32 * a + 255 * (255 - a) + 127) / 255) as u8;
        flat.put_pixel(x, y, [blend(px[0]), blend(px[1]), blend(px[2]), 255].into());
    }

    let mut out = Vec::new();
    image::codecs::jpeg::JpegEncoder::new_with_quality(&mut out, 90).encode_image(&flat)?;
    Ok(out)
}

/// Fetch the image at `url`, returning its raw bytes.
///
/// Unlike the Cover Art Archive lookup this is not rate limited: the user is
/// explicitly asking for a single image from a URL of their choosing. The
/// body is capped by ureq's default 10 MB limit.
pub fn fetch_image(url: &str) -> Result<Vec<u8>, Error> {
    let config = Config::builder()
        .user_agent(concat!("rend/", env!("CARGO_PKG_VERSION")))
        .timeout_global(Some(TIMEOUT))
        .build();
    let agent = Agent::new_with_config(config);
    match agent.get(url).call() {
        Ok(resp) => {
            let mut body = resp.into_body();
            let bytes = body
                .read_to_vec()
                .map_err(|e| Error::Network(e.to_string()))?;
            if bytes.is_empty() {
                Err(Error::NotFound)
            } else {
                Ok(bytes)
            }
        }
        Err(HttpError::StatusCode(404)) => Err(Error::NotFound),
        Err(HttpError::StatusCode(code)) => Err(Error::HttpStatus(code)),
        Err(e) => Err(Error::Network(e.to_string())),
    }
}

